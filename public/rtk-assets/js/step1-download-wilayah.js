// ============================================================
// VARIABEL GLOBAL WILAYAH (daftar kabkota terpilih)
// ============================================================
window.WILAYAH = window.WILAYAH || [];

// ============================================================
// Fungsi populate dropdown provinsi
// ============================================================
function populateProvinsi(selectId) {
  const sel = document.getElementById(selectId);
  if (!sel) return;
  sel.innerHTML = "";
  Object.entries(window.PROVINSI_DATA).forEach(([kode, nama]) => {
    const o = document.createElement("option");
    o.value = kode;
    o.textContent = nama;
    sel.appendChild(o);
  });
}

// ============================================================
// Fungsi load kabupaten/kota dari data embedded
// ============================================================
async function loadWilayah(kodeProv) {
  if (!kodeProv) {
    console.warn("Kode provinsi kosong");
    return;
  }

  const daftarKab = window.KABKOTA_DATA[String(kodeProv)];
  if (!daftarKab || daftarKab.length === 0) {
    console.warn("Data kabupaten/kota tidak ditemukan untuk provinsi:", kodeProv);
    WILAYAH.length = 0;
    return;
  }

  WILAYAH.length = 0;
  daftarKab.forEach(nama => WILAYAH.push(nama));

  console.log("WILAYAH OK:", WILAYAH);
}
